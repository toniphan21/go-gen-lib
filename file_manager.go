var ErrFileNotFound = errors.New("file not found")
var ErrGenFileNotFound = errors.New("GenFile not found")
var ErrCannotMakeGenFile = errors.New("cannot make GenFile")

type Output struct {
	PackageName    string
	SourceFileName string
	TestFileName   string
}

func (o *Output) Merge(others ...Output) {
	for _, other := range others {
		if strings.TrimSpace(other.PackageName) != "" {
			o.PackageName = other.PackageName
		}

		if strings.TrimSpace(other.SourceFileName) != "" {
			o.SourceFileName = other.SourceFileName
		}

		if strings.TrimSpace(other.TestFileName) != "" {
			o.TestFileName = other.TestFileName
		}
	}
}

type GenFile struct {
	FullPath string
	RelPath  string
	PkgPath  string
	PkgName  string
	jenFile  *jen.File
	actions  map[string]bool
}

func (f *GenFile) FilePath() string {
	return f.FullPath
}

func (f *GenFile) FileContent() []byte {
	return []byte(f.Content())
}

func (f *GenFile) JenFile() *jen.File {
	return f.jenFile
}

func (f *GenFile) Content() string {
	return f.jenFile.GoString()
}

func (f *GenFile) Once(action string, fn func()) *GenFile {
	if f.actions == nil {
		f.actions = make(map[string]bool)
	}

	if !f.actions[action] {
		fn()
	}

	f.actions[action] = true
	return f
}

var _ file.File = (*GenFile)(nil)

